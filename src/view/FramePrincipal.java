    private void buscarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_buscarActionPerformed
        // Crear una instancia del controlador1
        controlador1 con = new controlador1();

// Llamar al método buscar del controlador1 con el valor de InputCedula1 y el Panelincio como parámetros
        con.buscar(InputCedula1.getText(), Panelincio);

// Establecer el texto del componente idpersona con el valor de InputCedula1
        idpersona.setText(InputCedula1.getText());

// Obtener la identificación de la persona desde el componente idpersona
        String indetificacion = idpersona.getText();

// Llamar al método tablas del controlador1 con la tabla_elementos y la identificación como parámetros
        con.tablas(this.tabla_elementos, indetificacion);

// Limpiar el texto del componente InputCedula1
        InputCedula1.setText("");

    }//GEN-LAST:event_buscarActionPerformed

