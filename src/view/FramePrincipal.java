    private void btneditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btneditarActionPerformed
        // Crear una instancia del controlador1
        controlador1 con = new controlador1();

// Obtener valores de los campos de texto en la interfaz gráfica
        String serial = Txtserial.getText();
        String elemento = txtelemento.getText();
        String marca = txtmarca.getText();
        String descripcion = txtdescripcion.getText();
        String Cantidad = TxtCantidad.getText();
       // String user = idusuario.getText();

// Llamar al método Conactualizar del controlador1 con la tabla_elementos, nombre de usuario, y datos del elemento como parámetros
        con.Conactualizar(this.tabla_elementos,  serial, elemento, marca, descripcion, Cantidad);

// Actualizar la tabla después de la actualización de datos
        String indetificacion = idpersona.getText();
        con.tablas(this.tabla_elementos, indetificacion);

// Crear una instancia del controlador2 y pasar la referencia de la clase actual (this)
        controlador2 co2 = new controlador2(this);

// Llamar al método limpiarelemento del controlador2 para limpiar elementos en la interfaz gráfica
        co2.limpiarelemento();
    }//GEN-LAST:event_btneditarActionPerformed

